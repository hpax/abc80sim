int unicode_to_abc(int c)
{
    if (c != (wchar_t)c)
	return -1;

    switch (c) {
    case L' ':
	return ' ';
    case L'¤':
	return '$';
    case L'É':
	return '@';
    case L'Å':
	return ']';
    case L'Ä':
    case L'Æ':
	return '[';
    case L'Ö':
    case L'Ø':
	return '\\';
    case L'Ü':
	return '^';
    case L'é':
	return '`';
    case L'å':
	return '}';
    case L'ä':
    case L'æ':
	return '{';
    case L'ö':
    case L'ø':
	return '|';
    case L'ü':
	return '~';
    case L'§':
    case L'½':
	return 127;
    default:
	if (c == (uint8_t)c)
	    return c;
	else
	    return -1;
    }
}
